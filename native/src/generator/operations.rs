use super::{Result, array, json_text, object, string};
use serde_json::{Map, Value, json};
use std::collections::BTreeSet;

const METHODS: &[&str] = &["get", "post", "put", "patch", "delete", "head", "options"];

pub(super) fn bindings(document: &Value) -> Result<String> {
    let canonical: BTreeSet<_> = object(&document["components"]["schemas"], "OpenAPI schemas")?
        .iter()
        .filter(|(_, schema)| {
            schema.get("x-cirnet-contract").is_some()
                || schema.get("x-netcircuit-contract").is_some()
        })
        .map(|(name, _)| name.as_str())
        .collect();

    let mut records = Map::new();
    let mut declarations = Vec::new();
    let mut paths: Vec<_> = object(&document["paths"], "OpenAPI paths")?
        .iter()
        .collect();
    paths.sort_unstable_by_key(|(path, _)| path.as_str());
    // Sort path and method identities while preserving the supplied response,
    // media and parameter ordering within each operation.
    for (path, path_item) in paths {
        if !path.starts_with("/api/") {
            continue;
        }
        let mut methods: Vec<_> = object(path_item, "OpenAPI path item")?.iter().collect();
        methods.sort_unstable_by_key(|(method, _)| method.as_str());
        for (method, operation) in methods {
            if !METHODS.contains(&method.as_str()) {
                continue;
            }
            let name = string(&operation["operationId"], "operationId")?;
            if records.contains_key(name) {
                return Err(format!("Duplicate OpenAPI operation id {name}").into());
            }
            let (record, declaration) = binding(&canonical, path, method, path_item, operation)
                .map_err(|error| format!("OpenAPI operation {name}: {error}"))?;
            records.insert(name.to_owned(), record);
            declarations.push(format!(
                "  {}: {declaration}",
                json_text(&json!(name), false, true)?
            ));
        }
    }
    Ok(format!(
        "// Generated by scripts/export_openapi.py from FastAPI registrations; edit routes/canonical schemas.\n\
         import type * as DTO from './dto'\nexport interface ApiOperations {{\n{}\n}}\n\
         export const apiOperations = {} as const\nexport type OperationName = keyof ApiOperations\n",
        declarations.join("\n"),
        json_text(&Value::Object(records), true, true)?,
    ))
}

fn binding(
    canonical: &BTreeSet<&str>,
    path: &str,
    method: &str,
    path_item: &Value,
    operation: &Value,
) -> Result<(Value, String)> {
    let request_body = operation.get("requestBody");
    let request_contract = if let Some(body) =
        request_body.filter(|body| !body.as_object().is_some_and(Map::is_empty))
    {
        let content = object(&body["content"], "request body content")?;
        if content.len() != 1 || !content.contains_key("application/json") {
            return Err("Unsupported request media".into());
        }
        Some(contract(canonical, &content["application/json"]["schema"])?)
    } else {
        None
    };
    let request_type =
        request_contract.map_or_else(|| "undefined".into(), |name| format!("DTO.{name}"));
    let mut success_types = Vec::new();
    let mut error_types = Vec::new();
    let mut success_statuses = Vec::new();
    let mut response_media = Vec::new();
    let mut success_shape = None;
    let mut binary = false;
    let mut response_bindings = Map::new();
    for (status, response) in object(&operation["responses"], "responses")? {
        let success = status.starts_with('2');
        let mut bindings = Map::new();
        if success {
            success_statuses.push(status.parse::<u16>()?);
        }
        if let Some(content) = response.get("content") {
            for (media, description) in object(content, "response content")? {
                let schema = &description["schema"];
                let array = schema["type"] == "array";
                let is_binary = schema["format"] == "binary";
                let response_contract = if is_binary {
                    None
                } else {
                    Some(contract(
                        canonical,
                        if array { &schema["items"] } else { schema },
                    )?)
                };
                let ts_type = type_name(canonical, schema)?;
                if success {
                    check_success_shape(&mut success_shape, (response_contract, array))?;
                    append_unique(&mut success_types, ts_type);
                    append_unique(&mut response_media, media.as_str());
                    binary |= is_binary;
                } else {
                    append_unique(&mut error_types, ts_type);
                }
                bindings.insert(
                    media.clone(),
                    json!({
                        "contract": response_contract,
                        "array": array,
                        "binary": is_binary,
                    }),
                );
            }
        }
        if success && bindings.is_empty() {
            if !matches!(status.as_str(), "204" | "205") {
                return Err(format!("Undocumented success response {status}").into());
            }
            check_success_shape(&mut success_shape, (None, false))?;
            append_unique(&mut success_types, "undefined".into());
        }
        response_bindings.insert(status.clone(), Value::Object(bindings));
    }
    let (response_contract, response_array) = success_shape.ok_or("No success response")?;
    if error_types.is_empty() {
        return Err("No documented error DTO".into());
    }

    let mut parameters = Vec::new();
    for item in [path_item, operation] {
        if let Some(values) = item.get("parameters") {
            parameters.extend(array(values, "operation parameters")?);
        }
    }
    let declarations = format!(
        "{{ request: {request_type}; response: {}; path: {}; query: {}; headers: {}; error: {} }}",
        success_types.join(" | "),
        parameter_type(canonical, &parameters, "path")?,
        parameter_type(canonical, &parameters, "query")?,
        parameter_type(canonical, &parameters, "header")?,
        error_types.join(" | "),
    );
    Ok((
        json!({
            "method": method.to_ascii_uppercase(),
            "path": path,
            "requestContract": request_contract,
            "requestBodyRequired": request_body.and_then(|body| body["required"].as_bool()).unwrap_or(false),
            "responseContract": response_contract,
            "responseArray": response_array,
            "responseMedia": response_media,
            "successStatuses": success_statuses,
            "binary": binary,
            "responses": response_bindings,
        }),
        declarations,
    ))
}

fn check_success_shape<'a>(
    existing: &mut Option<(Option<&'a str>, bool)>,
    shape: (Option<&'a str>, bool),
) -> Result<()> {
    if *existing.get_or_insert(shape) != shape {
        return Err("Incompatible success DTOs; use explicit operation variants".into());
    }
    Ok(())
}

fn append_unique<T: PartialEq>(items: &mut Vec<T>, item: T) {
    if !items.contains(&item) {
        items.push(item);
    }
}

fn contract<'a>(canonical: &BTreeSet<&str>, schema: &'a Value) -> Result<&'a str> {
    let name = schema["$ref"]
        .as_str()
        .and_then(|reference| reference.strip_prefix("#/components/schemas/"))
        .ok_or_else(|| format!("Operation DTO must use a named canonical schema: {schema}"))?;
    let name = name.strip_suffix("-Input").unwrap_or(name);
    let name = name.strip_suffix("-Output").unwrap_or(name);
    if !canonical.contains(name) {
        return Err(format!("Operation references a noncanonical DTO: {name}").into());
    }
    Ok(name)
}

fn type_name(canonical: &BTreeSet<&str>, schema: &Value) -> Result<String> {
    if schema.get("$ref").is_some() {
        return Ok(format!("DTO.{}", contract(canonical, schema)?));
    }
    if let Some(values) = schema.get("enum") {
        let types = array(values, "parameter enum")?
            .iter()
            .map(|value| json_text(value, false, true))
            .collect::<Result<Vec<_>>>()?;
        return Ok(types.join(" | "));
    }
    if let Some(value) = schema.get("const") {
        return json_text(value, false, true);
    }
    for key in ["anyOf", "oneOf"] {
        if let Some(values) = schema.get(key) {
            let types = array(values, key)?
                .iter()
                .map(|value| type_name(canonical, value))
                .collect::<Result<Vec<_>>>()?;
            return Ok(types.join(" | "));
        }
    }
    match schema["type"].as_str() {
        Some("array") => Ok(format!(
            "Array<{}>",
            type_name(canonical, &schema["items"])?
        )),
        Some("string") if schema["format"] == "binary" => Ok("ArrayBuffer".into()),
        Some(kind @ ("string" | "boolean" | "null")) => Ok(kind.into()),
        Some("integer" | "number") => Ok("number".into()),
        _ => Err(format!("Unsupported anonymous operation schema: {schema}").into()),
    }
}

fn parameter_type(
    canonical: &BTreeSet<&str>,
    parameters: &[&Value],
    location: &str,
) -> Result<String> {
    let mut fields = Vec::new();
    for parameter in parameters.iter().filter(|p| p["in"] == location) {
        fields.push(format!(
            "{}{}: {}",
            json_text(
                &json!(string(&parameter["name"], "parameter name")?),
                false,
                true
            )?,
            if parameter["required"].as_bool().unwrap_or(false) {
                ""
            } else {
                "?"
            },
            type_name(canonical, &parameter["schema"])?,
        ));
    }
    if fields.is_empty() {
        Ok("Record<string, never>".into())
    } else {
        Ok(format!("{{ {} }}", fields.join("; ")))
    }
}
